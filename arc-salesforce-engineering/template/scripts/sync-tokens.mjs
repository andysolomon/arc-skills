#!/usr/bin/env node
// Writes the org's token module from arc-design/tokens.css, applying arc-design's host
// exception for Salesforce: the light values (Lightning is a light host), Salesforce blue
// as the accent, and :host as the selector (a component's styles can't reach :root).
//
//   node scripts/sync-tokens.mjs <arc-design>/tokens.css           write the module
//   node scripts/sync-tokens.mjs <arc-design>/tokens.css --check   fail if it is out of date
import { readFileSync, writeFileSync, existsSync } from 'node:fs';

const OUT = new URL('../force-app/main/default/lwc/arcTokens/arcTokens.css', import.meta.url).pathname;
const HOST = { '--hi': '#0176d3', '--on-hi': '#fff' };

const [source, flag] = process.argv.slice(2);
if (!source || !existsSync(source)) {
  console.error('usage: node scripts/sync-tokens.mjs <arc-design>/tokens.css [--check]');
  process.exit(2);
}
const css = readFileSync(source, 'utf8').replace(/\/\*[\s\S]*?\*\//g, '');
const start = css.search(/@media\s*\(\s*prefers-color-scheme\s*:\s*light\s*\)/);
if (start < 0) { console.error(`FAIL ${source}: no light block`); process.exit(1); }
let depth = 0, end = css.indexOf('{', start);
for (let i = end; i < css.length; i++) {
  if (css[i] === '{') depth++;
  else if (css[i] === '}' && --depth === 0) { end = i; break; }
}
const decls = (block) => new Map([...block.matchAll(/(--[\w-]+)\s*:\s*([^;]+);/g)].map((m) => [m[1], m[2].trim()]));
const tokens = new Map([...decls(css.slice(0, start) + css.slice(end + 1)), ...decls(css.slice(start, end + 1)), ...Object.entries(HOST)]);

const body = [...tokens].map(([k, v]) => `  ${k}:${v};`).join('\n');
const out = `/* Generated by scripts/sync-tokens.mjs from arc-design/tokens.css. Don't edit; run it again.
   arc-design's host exception for Salesforce: light values, Salesforce blue accent. */
:host{
  color-scheme:light;
${body}
}
`;

if (flag === '--check') {
  const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  if (current !== out) { console.log('FAIL arcTokens.css is out of date: run node scripts/sync-tokens.mjs <arc-design>/tokens.css'); process.exit(1); }
  console.log('PASS arcTokens.css matches arc-design/tokens.css with the Salesforce host exception');
} else {
  writeFileSync(OUT, out);
  console.log(`wrote ${OUT}`);
}
