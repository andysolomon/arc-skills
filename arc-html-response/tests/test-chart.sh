#!/usr/bin/env bash
# Tests for scripts/chart.mjs. Run: bash arc-html-response/tests/test-chart.sh
set -u

here=$(cd "$(dirname "$0")" && pwd)
skill=$(dirname "$here")
chart="$skill/scripts/chart.mjs"
lint="$skill/scripts/lint.sh"
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT
pass=0 fail=0

ok()  { echo "ok      $1"; pass=$((pass + 1)); }
bad() { echo "not ok  $1"; [ -n "${2:-}" ] && printf '%s\n' "$2" | sed 's/^/        /'; fail=$((fail + 1)); }
has() { # has <name> <needle> <haystack>
  if grep -qF -- "$2" <<<"$3"; then ok "$1"; else bad "$1" "$3"; fi
}

# The line chart reproduces the kit's example exactly (the kit's example is generated by it).
out=$(node "$chart" line --slug latency --title "p95 latency by week" --labels W1,W2,W3,W4,W5,W6,W7,W8 --values 420,390,410,350,330,300,310,280 --unit " ms")
kitpts=$(grep -o 'class="series" pathLength="1" points="[^"]*"' "$skill/components.html" | head -1)
has "line points match the kit example" "$kitpts" "$out"
has "line has prefixed title and desc" 'aria-labelledby="latency-title latency-desc"' "$out"
has "line labels the last point" '>280 ms</text>' "$out"
has "line ships raw numbers" '<summary>Raw numbers</summary>' "$out"

out=$(node "$chart" line --slug big --title t --labels a,b,c --values 1200,98000,45000)
has "large axis ticks are compact" '>100k</text>' "$out"

out=$(node "$chart" bars --labels esbuild,Vite,webpack --values 1.2,2.9,9.8 --unit " s" --key esbuild)
has "bars scale to the largest value" 'style="--v:100;--i:0"><div class="lbl">webpack' "$out"
out0=$(node "$chart" bars --labels a,b --values 0,2)
has "a zero bar gets no fill" 'class="bar is-zero" style="--v:0' "$out0"
has "bars mark the key bar" '<div class="bar is-key" style="--v:12.2;--i:2"><div class="lbl">esbuild' "$out"
has "bars carry an aria-label" 'aria-label="webpack 9.8 s, Vite 2.9 s, esbuild 1.2 s"' "$out"

out=$(node "$chart" bars --labels "a<b,c" --values 1,2)
has "labels are escaped" 'a&lt;b' "$out"

out=$(node "$chart" donut --slug coverage --title "Line coverage" --part 18 --whole 25 --noun files)
has "donut dasharray is share and rest" 'stroke-dasharray="72 28"' "$out"
has "donut shows the denominator" '18 / 25 files' "$out"

out=$(node "$chart" bars --title "Runs by trigger" --labels Loop,Typing --values 56,1 --unit " run| runs" --cols "trigger,runs")
has "bars title prefixes the aria-label" 'aria-label="Runs by trigger: Loop 56 runs, Typing 1 run"' "$out"
has "unit picks the singular for 1" '>1 run</span>' "$out"
has "cols name the raw table" '<th>trigger</th><th>runs</th>' "$out"

out=$(node "$chart" donut --slug f --title Flaky --part 3 --whole 40 --noun runs)
has "small shares keep one decimal" '>7.5%</text>' "$out"

out=$(node "$chart" --help); code=$?
if [ "$code" -eq 0 ] && grep -q -- '--cols' <<<"$out"; then ok "--help prints every flag"; else bad "--help prints every flag" "exit $code"; fi

# Bad input exits 2 with a reason.
for args in "line --slug x --title t --labels a,b --values 1,z" \
            "bars --labels a,b --values 1" \
            "bars --labels a,b --values 1,-2" \
            "donut --slug c --title t --part 30 --whole 25" \
            "line --slug Bad_Slug --title t --labels a,b --values 1,2" \
            "pie --values 1"; do
  # shellcheck disable=SC2086
  err=$(node "$chart" $args 2>&1 >/dev/null); code=$?
  if [ "$code" -eq 2 ] && [ -n "$err" ]; then ok "rejects: $args"; else bad "rejects: $args" "exit $code: $err"; fi
done

# All three outputs, dropped into a page with the kit's CSS, pass the lint.
css=$(awk '/\/\* component: (bars|line|donut|details) /{p=1} /\/\* component: (stacked|heat|flow|diagram|timeline|compare|findings|changes|decisions|tabs) /{p=0} p' "$skill/components.html")
{
  printf '<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"><title>Chart Test</title><style>:root{--fg:#fff;--dim:#aaa;--line:#333;--surface:#111;--hi:#f39;--mono:monospace;--sans:sans-serif;--ease:ease}\n%s\n</style></head><body>\n' "$css"
  node "$chart" bars --labels a,b --values 1,2
  node "$chart" line --slug l --title "A line" --labels a,b,c --values 1,3,2
  node "$chart" donut --slug d --title "A donut" --part 1 --whole 4
  printf '</body></html>\n'
} > "$work/page.html"
lout=$(DIAGRAM_DESIGN_DIR=none bash "$lint" "$work/page.html" 2>&1)
if [ $? -eq 0 ]; then ok "generated markup passes lint"; else bad "generated markup passes lint" "$lout"; fi

echo "--- $pass passed, $fail failed"
[ "$fail" -eq 0 ]
